"""Generate the dext's command-policy table from docs/protocol/policy-table.json.

Usage (from the repo root):
  python3 -I Tools/policygen/policygen.py           write Driver/XLRDriver/PolicyTable.generated.h
  python3 -I Tools/policygen/policygen.py --check   fail if that file is out of date

Both modes also check that the categories in policy-table.json are exactly the
ones in SPEC.md section 8's table (ADR 0003 consequence 3: one source).
"""

import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
TABLE = ROOT / "docs/protocol/policy-table.json"
SPEC = ROOT / "docs/protocol/SPEC.md"
OUTPUT = ROOT / "Driver/XLRDriver/PolicyTable.generated.h"

GATES = {None: "Gate::none", "animations": "Gate::animations", "submix": "Gate::submix", "mix2": "Gate::mix2"}
CLASSES = {"read": "Class::read", "write": "Class::write"}


def number(text):
    text = str(text)
    return int(text, 16) if text.lower().startswith("0x") else int(text)


def ranges(items):
    out = []
    for item in items:
        lo, _, hi = str(item).partition("-")
        out.append((number(lo), number(hi or lo)))
    return out


def spec_categories():
    section = SPEC.read_text().split("## 8.", 1)[1].split("\n## ", 1)[0]
    return {int(m, 16) for m in re.findall(r"^\| (0x[0-9A-F]{3}) \|", section, re.M)}


def emit_ranges(name, items):
    if not items:
        return f"constexpr const Range * {name} = nullptr;"
    body = ", ".join(f"{{0x{lo:X}, 0x{hi:X}}}" for lo, hi in items)
    return f"constexpr Range {name}[] = {{{body}}};"


def emit_values(name, items, ctype):
    if not items:
        return f"constexpr const {ctype} * {name} = nullptr;"
    return f"constexpr {ctype} {name}[] = {{{', '.join(f'0x{number(v):X}' for v in items)}}};"


def generate(table):
    lines = [
        "// Generated by Tools/policygen/policygen.py from docs/protocol/policy-table.json.",
        "// Do not edit; change the JSON (and SPEC.md section 8) and regenerate.",
        "",
        "#pragma once",
        "",
        '#include "PolicyTypes.h"',
        "",
        "namespace xlr::policy::table {",
        "",
    ]
    for model in ("mini", "full"):
        g = table["gates"][model]
        parts = ", ".join("{" + ", ".join(str(x) for x in g[k]) + "}" for k in ("animations", "submix", "mix2"))
        lines.append(f"constexpr GateVersions k{model.capitalize()}Gates = {{{parts}}};")
    lines.append("")
    for name, items in table["key_sets"].items():
        lines.append(emit_ranges(f"k{name.capitalize()}Keys", ranges(items)))
    lines.append("")
    rules = []
    for command in table["commands"]:
        c = number(command["category"])
        prefix = f"k{c:03X}"
        lines.append(emit_ranges(f"{prefix}Indices", ranges(command["indices"])))
        gated = command.get("gated_indices")
        lines.append(emit_ranges(f"{prefix}GatedIndices", ranges(gated["indices"]) if gated else []))
        lines.append(emit_ranges(f"{prefix}IdentityIndices", ranges(command.get("identity_indices", []))))
        values = command.get("values", {})
        kind = values.get("kind")
        lines.append(emit_values(f"{prefix}Even", values.get("even", []), "uint8_t"))
        lines.append(emit_values(f"{prefix}Odd", values.get("odd", []), "uint8_t"))
        lines.append(emit_values(f"{prefix}Last", values.get("last", []), "uint8_t"))
        lines.append(emit_values(f"{prefix}AllowedBytes", values.get("allowed", []) if kind == "bytes-in" else [], "uint8_t"))
        lines.append(emit_values(f"{prefix}KeyAllowed", values.get("allowed", []) if kind == "key-pairs" else [], "uint32_t"))
        lines.append(emit_values(f"{prefix}KeyRisk", values.get("hardware_risk", []), "uint32_t"))

        length = command["length"]
        if length == "pairs":
            length_fields = ".lengthKind = LengthKind::pairs"
        elif isinstance(length, dict):
            length_fields = (f".lengthKind = LengthKind::gated, .lengthGate = {GATES[length['gate']]}, "
                             f".lengthAtGate = {length['at_gate']}, .lengthBelowGate = {length['below_gate']}")
        else:
            length_fields = f".lengthKind = LengthKind::exact, .length = {length}"
        value_kind = {None: "none", "key-pairs": "keyPairs", "routing": "routing", "u32-max": "u32Max",
                      "bytes-max": "bytesMax", "bytes-in": "bytesIn"}[kind]
        fields = [
            f".category = 0x{c:X}",
            f".indices = {prefix}Indices, .indexCount = {len(command['indices'])}",
            f".gatedIndices = {prefix}GatedIndices, .gatedIndexCount = {len(gated['indices']) if gated else 0}, "
            f".indexGate = {GATES[gated['gate'] if gated else None]}",
            f".commandGate = {GATES[command.get('gate')]}",
            length_fields,
            f".valueKind = ValueKind::{value_kind}",
        ]
        if kind == "key-pairs":
            keys = table["key_sets"][values["keys"]]
            fields.append(f".keys = k{values['keys'].capitalize()}Keys, .keyCount = {len(keys)}")
            if "key" in values:
                fields.append(f".hasSpecialKey = true, .specialKey = 0x{number(values['key']):X}, "
                              f".specialAllowed = {prefix}KeyAllowed, .specialAllowedCount = {len(values['allowed'])}, "
                              f".specialRisk = {prefix}KeyRisk, .specialRiskCount = {len(values['hardware_risk'])}")
        if kind == "routing":
            fields.append(f".even = {prefix}Even, .evenCount = {len(values['even'])}, "
                          f".odd = {prefix}Odd, .oddCount = {len(values['odd'])}, "
                          f".last = {prefix}Last, .lastCount = {len(values['last'])}")
        if kind in ("u32-max", "bytes-max"):
            fields.append(f".maxValue = {values['max']}")
        if kind == "bytes-in":
            fields.append(f".allowedBytes = {prefix}AllowedBytes, .allowedByteCount = {len(values['allowed'])}")
        fields.append(f".reply = {command['reply']}")
        by_index = command.get("reply_by_index", {})
        if by_index:
            (index, size), = by_index.items()
            fields.append(f".hasReplyOverride = true, .replyOverrideIndex = {number(index)}, .replyOverrideMax = {size}")
        fields.append(f".commandClass = {CLASSES[command['class']]}")
        fields.append(f".tier = {command.get('tier', 0)}")
        fields.append(f".identityIndices = {prefix}IdentityIndices, "
                      f".identityIndexCount = {len(command.get('identity_indices', []))}")
        rules.append("    {" + ",\n     ".join(fields) + "},")
        lines.append("")
    lines.append("constexpr Rule kRules[] = {")
    lines.extend(rules)
    lines.append("};")
    lines.append("")
    lines.append("} // namespace xlr::policy::table")
    lines.append("")
    return "\n".join(lines)


def main():
    table = json.loads(TABLE.read_text())
    for c in table["commands"]:
        if (c["class"] == "write") != (1 <= c.get("tier", 0) <= 9):
            print(f"{c['category']}: write commands need a tier 1-9 and reads none (PROMPT.md Phase 5)")
            return 1
    categories = {number(c["category"]) for c in table["commands"]}
    spec = spec_categories()
    if categories != spec:
        print(f"policy-table.json and SPEC.md section 8 disagree: only in JSON {sorted(map(hex, categories - spec))}, "
              f"only in SPEC {sorted(map(hex, spec - categories))}")
        return 1
    text = generate(table)
    if "--check" in sys.argv[1:]:
        current = OUTPUT.read_text() if OUTPUT.exists() else ""
        if current != text:
            print(f"{OUTPUT.relative_to(ROOT)} is out of date; run python3 -I Tools/policygen/policygen.py")
            return 1
        print(f"{OUTPUT.relative_to(ROOT)} is current ({len(table['commands'])} commands)")
        return 0
    OUTPUT.write_text(text)
    print(f"wrote {OUTPUT.relative_to(ROOT)} ({len(table['commands'])} commands)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
